const required = (name) => {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is required. Add it to .env before importing images.`);
  return value;
};

const pexelsKey = required('PEXELS_API_KEY');
const cloudName = required('NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME');
const cloudinaryKey = required('CLOUDINARY_API_KEY');
const cloudinarySecret = required('CLOUDINARY_API_SECRET');

const slugify = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

async function searchPexels(query) {
  const response = await fetch(
    `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=1&orientation=landscape`,
    {
      headers: { Authorization: pexelsKey },
    },
  );
  if (!response.ok) throw new Error(`Pexels search failed for ${query}: ${response.status}`);
  const data = await response.json();
  const photo = data.photos?.[0];
  if (!photo?.src?.large2x) throw new Error(`No Pexels photo found for ${query}`);
  return photo.src.large2x;
}

async function uploadToCloudinary(sourceUrl, slug) {
  const timestamp = Math.floor(Date.now() / 1000);
  const publicId = `cafera/recipes/${slug}`;
  const signature = crypto
    .createHash('sha1')
    .update(`public_id=${publicId}&timestamp=${timestamp}${cloudinarySecret}`)
    .digest('hex');
  const body = new URLSearchParams({
    file: sourceUrl,
    api_key: cloudinaryKey,
    timestamp: String(timestamp),
    public_id: publicId,
    signature,
  });
  const response = await fetch(`https://api.cloudinary.com/v1_1/${cloudName}/image/upload`, {
    method: 'POST',
    body,
  });
  if (!response.ok)
    throw new Error(
      `Cloudinary upload failed for ${slug}: ${response.status} ${await response.text()}`,
    );
  const data = await response.json();
  return `https://res.cloudinary.com/${cloudName}/image/upload/f_auto,q_auto,w_1200/${data.public_id}.${data.format}`;
}

const images = {};
for (const recipe of recipes) {
  const slug = slugify(recipe);
  process.stdout.write(`Importing ${recipe}... `);
  const sourceUrl = await searchPexels(`${recipe} coffee`);
  images[slug] = await uploadToCloudinary(sourceUrl, slug);
  console.log('done');
}

const output = `/** Generated by \`npm run images:import\`. Do not edit manually. */\nexport const GENERATED_RECIPE_IMAGES: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`;
await fs.writeFile('src/lib/seed/recipe-images.generated.ts', output, 'utf8');
console.log(`Wrote ${Object.keys(images).length} unique Cloudinary recipe images.`);
